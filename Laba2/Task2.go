package main

import (
	"fmt"
)

func Number(n int) string {
	if n > 0 {
		return "Positive"
	} else if n < 0 {
		return "Negative"
	} else {
		return "Zero"
	}
}

func main() {
	var n int
	fmt.Println("Введите число:")
	fmt.Scan(&n)
	fmt.Println("Число:", Number(n))
}

